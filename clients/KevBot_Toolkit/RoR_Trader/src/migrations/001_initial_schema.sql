-- 7. SEED DATA (built-in records with user_id IS NULL)
-- ============================================================
-- Built-in requirement sets are seeded by the migration script
-- (src/migrate_json_to_db.py) which reads the current requirements.json
-- and inserts records with user_id IS NULL and built_in = true.
--
-- Built-in webhook templates are similarly seeded from webhook_templates.json.
-- This ensures the exact rule values stay in sync with the codebase.
