-- ============================================================
-- 1. CORE ENTITY TABLES
-- ============================================================

-- Strategies: the central entity — one row per saved strategy
CREATE TABLE strategies (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name TEXT NOT NULL,
    symbol TEXT NOT NULL,
    direction TEXT NOT NULL DEFAULT 'LONG',
    timeframe TEXT NOT NULL DEFAULT '1Min',
    strategy_origin TEXT NOT NULL DEFAULT 'standard',
    forward_testing BOOLEAN DEFAULT true,
    forward_test_start TIMESTAMPTZ,
    alert_tracking_enabled BOOLEAN DEFAULT false,
    alert_tracking_reset_at TIMESTAMPTZ,
    -- config JSONB holds all trigger/confluence/risk/lookback params
    -- (see Strategy Config JSONB Schema in Implementation_Spec_Phase_22.md)
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Backtest results (large blobs)
    kpis JSONB,
    stored_trades JSONB,
    equity_curve_data JSONB,
    -- Forward test / alert tracking results
    live_executions JSONB DEFAULT '[]'::jsonb,
    discrepancies JSONB DEFAULT '[]'::jsonb,
    discrepancies_dismissed_at TIMESTAMPTZ,
    data_refreshed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_strategies_user ON strategies(user_id);
CREATE INDEX idx_strategies_user_symbol ON strategies(user_id, symbol);

-- Portfolios: groups of strategies with allocation and account tracking
CREATE TABLE portfolios (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    name TEXT NOT NULL,
    starting_balance NUMERIC DEFAULT 10000,
    compound_rate NUMERIC DEFAULT 1.0,
    requirement_set_id INTEGER,
    -- strategies is [{strategy_id, risk_per_trade}, ...]
    strategies JSONB DEFAULT '[]'::jsonb,
    cached_kpis JSONB,
    equity_curve_data JSONB,
    -- account tracking: {starting_balance, ledger: [...], notes, notes_updated_at}
    account JSONB,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_portfolios_user ON portfolios(user_id);

-- Requirement Sets: prop firm rules and custom rule sets
-- user_id IS NULL = built-in (shared across all users, read-only)
CREATE TABLE requirement_sets (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    built_in BOOLEAN DEFAULT false,
    firm_key TEXT,
    rules JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_requirements_user ON requirement_sets(user_id);

-- ============================================================
-- 2. ALERT SYSTEM TABLES
-- ============================================================

-- Alerts: signal records generated by Ralph engine or legacy monitor
CREATE TABLE alerts (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    -- Queryable fields for filtering/display
    type TEXT NOT NULL,                 -- 'entry_signal' or 'exit_signal'
    strategy_id INTEGER NOT NULL,
    strategy_name TEXT NOT NULL,
    symbol TEXT NOT NULL,
    direction TEXT NOT NULL,
    timeframe TEXT NOT NULL,
    source TEXT DEFAULT 'ralph',        -- 'ralph' or 'monitor'
    acknowledged BOOLEAN DEFAULT false,
    webhook_sent BOOLEAN DEFAULT false,
    -- Full alert payload (trigger, prices, portfolio context, webhook deliveries, etc.)
    data JSONB NOT NULL DEFAULT '{}'::jsonb,
    timestamp TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_alerts_user ON alerts(user_id);
CREATE INDEX idx_alerts_strategy ON alerts(user_id, strategy_id);
CREATE INDEX idx_alerts_timestamp ON alerts(user_id, timestamp DESC);

-- Alert Configuration: per-user global/strategy/portfolio alert settings
-- Stores the full alert_config.json structure as a single JSONB document
CREATE TABLE alert_config (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Webhook Templates: reusable payload templates for webhook delivery
-- user_id IS NULL = built-in defaults (shared, read-only)
CREATE TABLE webhook_templates (
    id TEXT PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category TEXT,
    is_default BOOLEAN DEFAULT false,
    payload_template TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_webhook_templates_user ON webhook_templates(user_id);

-- Inbound Webhook Signals: external signals received via webhook endpoint
CREATE TABLE inbound_signals (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    strategy_id INTEGER,
    payload JSONB NOT NULL,
    processed BOOLEAN DEFAULT false,
    received_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_inbound_signals_user ON inbound_signals(user_id, processed);

-- ============================================================
-- 3. ENGINE & MONITOR TABLES
-- ============================================================

-- Monitor Status: Ralph engine control and status (one row per user)
-- Web UI writes desired_state; worker reads it and starts/stops Ralph
-- Worker writes actual status back to the status JSONB column
CREATE TABLE monitor_status (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    desired_state TEXT DEFAULT 'stopped',   -- 'running' or 'stopped'
    -- Full engine status blob: {running, connected, symbols, strategies, tick_count, ...}
    status JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- Position state blob: {positions: {strategy_id: {status, entry_price, ...}}}
    engine_state JSONB NOT NULL DEFAULT '{}'::jsonb,
    last_heartbeat TIMESTAMPTZ,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Engine Audit Log: fidelity audit trail from Ralph engine
-- Append-only log of bar closes with indicator/trigger/position snapshots
CREATE TABLE engine_audit_log (
    id BIGSERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL,
    ts TIMESTAMPTZ NOT NULL,            -- bar close timestamp
    symbol TEXT NOT NULL,
    timeframe INTEGER NOT NULL,         -- seconds (60, 300, 900, etc.)
    bar_close NUMERIC NOT NULL,
    indicators JSONB,
    triggers JSONB,
    interpreters JSONB,
    positions JSONB,
    created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX idx_audit_user_ts ON engine_audit_log(user_id, ts DESC);
CREATE INDEX idx_audit_user_symbol ON engine_audit_log(user_id, symbol, ts DESC);

-- ============================================================
-- 4. USER CONFIG TABLES (one row per user, JSONB document)
-- ============================================================

-- User Settings: app preferences (chart_visible_candles, data_feed, timezone, etc.)
CREATE TABLE user_settings (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    settings JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Confluence Groups: indicator group configurations
CREATE TABLE confluence_groups (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    groups JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- General Packs: time-of-day, session, day-of-week, calendar filters
CREATE TABLE general_packs (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    packs JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Risk Management Packs: stop-loss and take-profit configurations
CREATE TABLE risk_management_packs (
    id SERIAL PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE NOT NULL UNIQUE,
    packs JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- ============================================================
-- 5. PUBLIC / WAITLIST TABLE
-- ============================================================

-- Pre-registration waitlist (no auth required for insert)
CREATE TABLE waitlist (
    id SERIAL PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    name TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

